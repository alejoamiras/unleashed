/// <reference types="node" />
/**
 * Regenerates `src/core/icons.ts` from Pixelarticons (MIT) at a pinned commit:
 * `bun packages/design/scripts/vendor-icons.ts`. A local one-off that needs the network and a
 * logged-in `gh`; CI only compiles its output. Each SVG is checked against the git blob id GitHub lists for its path at
 * that commit, and only `<path d>` data crosses into the bundle.
 */
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const REPO = "halfmage/pixelarticons"
/** Tag v2.4.0. */
const COMMIT = "9e6658cdb790ef03deafdb482867b0cc995b1288"

